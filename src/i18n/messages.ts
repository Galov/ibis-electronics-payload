export const messages: Record<Locale, Messages> = { bg, en }

export type MessageKey = keyof typeof bg
export type MessageValues = Record<string, string | number>
export function formatMessage(locale: Locale, key: MessageKey, values: MessageValues = {}): string {
  return messages[locale][key].replace(/\{(\w+)\}/g, (match, name: string) =>
    Object.prototype.hasOwnProperty.call(values, name) ? String(values[name]) : match,
  )
}
